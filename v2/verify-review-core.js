"use strict";
const assert=require("node:assert/strict");
const {dateKey,plusDays,keyFor,grade,dueBatch}=require("./review-core.js");
assert.equal(plusDays("2026-12-31",1),"2027-01-01");
assert.throws(()=>dateKey("2026-02-30"));
assert.notEqual(keyFor({kind:"verb",id:"書く",skill:"て形"}),keyFor({kind:"verb",id:"書く",skill:"ない形"}));
let r;
r=grade(r,{day:"2026-11-02",type:"choice",correct:true});assert.equal(r.stars,1);
r=grade(r,{day:"2026-11-02",type:"choice",correct:true});assert.equal(r.stars,1,"same-day repeat");
r=grade(r,{day:"2026-11-03",type:"choice",correct:true});assert.equal(r.stars,2);
r=grade(r,{day:"2026-11-04",type:"choice",correct:true});assert.equal(r.stars,3);
r=grade(r,{day:"2026-11-05",type:"choice",correct:true});assert.equal(r.stars,3,"one format caps at three stars");
r=grade(r,{day:"2026-11-06",type:"input",correct:true});assert.equal(r.stars,4);
r=grade(r,{day:"2026-11-07",type:"input",correct:true});assert.equal(r.stars,4,"two formats cap at four stars");
r=grade(r,{day:"2026-11-08",type:"listening",correct:true});assert.equal(r.stars,5);
r=grade(r,{day:"2026-11-09",type:"listening",correct:false});assert.equal(r.stars,4);assert.equal(r.due,"2026-11-09");
r=grade(r,{day:"2026-11-09",type:"choice",correct:true,hint:true});assert.equal(r.stars,4,"hint must not promote");
const x=grade(undefined,{day:"2026-11-01",correct:true,type:"input"});
const y=grade(undefined,{day:"2026-11-02",correct:false,type:"input"});
const input={a:x,b:y,c:r,notDue:{stars:5,due:"2026-12-01"}};
assert.deepEqual(dueBatch(input,"2026-11-09",{limit:2}),["b","a"]);
assert.deepEqual(dueBatch(input,"2026-11-09",{limit:4,exclude:["b"]}),["a","c"]);
assert.equal(input.c.stars,4,"batch selector must not mutate original data");
console.log("PASS — date keys, per-form identity, cross-day stars, hints, mistakes, batch overdue order");
